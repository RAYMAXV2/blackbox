// Renders the cause -> consequence -> fix knowledge base as Markdown (docs/SIGNATURES.md).
// Usage: node scripts/gen-signatures-doc.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const kb = JSON.parse(readFileSync(join(root, 'crates/blackbox-core/kb/signatures.json'), 'utf8'))

const CONSEQUENCES = {
  en: { stutter: 'stutter', freeze: 'freeze', audio_crackle: 'audio crackle', input_lag: 'input lag', fps_drop: 'FPS drop', slow_app: 'slow app' },
  fr: { stutter: 'saccades', freeze: 'gel', audio_crackle: 'craquements audio', input_lag: 'latence des entrées', fps_drop: 'chute de FPS', slow_app: 'appli lente' },
}
const CATEGORIES = {
  en: { driver: 'Drivers', disk: 'Disk', memory: 'Memory', process: 'Background processes', cpu: 'CPU', gpu: 'GPU', app: 'The app itself', system: 'System' },
  fr: { driver: 'Pilotes', disk: 'Disque', memory: 'Mémoire', process: 'Processus en arrière-plan', cpu: 'Processeur', gpu: 'Carte graphique', app: "L'appli elle-même", system: 'Système' },
}
const HEAD = {
  en: { title: 'Causes → consequences → fixes', intro: 'Every verdict Blackbox can give. Placeholders in braces are filled with what was measured.', cause: 'Cause', cons: 'Consequences', fixes: 'Fixes' },
  fr: { title: 'Causes → conséquences → solutions', intro: 'Tous les verdicts que Blackbox peut donner. Les valeurs entre accolades sont remplies avec ce qui a été mesuré.', cause: 'Cause', cons: 'Conséquences', fixes: 'Solutions' },
}
const esc = (s) => s.replace(/\|/g, '\\|')

let md = '<!-- Generated by scripts/gen-signatures-doc.mjs from crates/blackbox-core/kb/signatures.json. Do not edit. -->\n\n'
for (const lang of ['en', 'fr']) {
  const h = HEAD[lang]
  md += `# ${h.title}${lang === 'fr' ? ' (FR)' : ''}\n\n${h.intro}\n\n`
  for (const [cat, label] of Object.entries(CATEGORIES[lang])) {
    const entries = kb.filter((e) => e.category === cat)
    if (!entries.length) continue
    md += `## ${label}\n\n| ${h.cause} | ${h.cons} | ${h.fixes} |\n| --- | --- | --- |\n`
    for (const e of entries) {
      const cons = e.consequences.map((c) => CONSEQUENCES[lang][c]).join(', ')
      const fixes = e.fixes.map((f) => esc(f[lang])).join('<br>')
      md += `| **${esc(e.title[lang])}**<br>${esc(e.explain[lang])}<br><sub>\`${e.id}\`</sub> | ${cons} | ${fixes} |\n`
    }
    md += '\n'
  }
}
writeFileSync(join(root, 'docs/SIGNATURES.md'), md)
console.log(`docs/SIGNATURES.md: ${kb.length} causes`)
