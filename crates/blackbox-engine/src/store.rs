//! On-disk persistence: settings and incidents.
//!
//! Layout under the data directory:
//!   settings.json
//!   incidents/index.json      summaries, newest first (small, loaded at start)
//!   incidents/<id>.json       full incident with its timeline (loaded on demand)
//!
//! Nothing is written unless something changed; writes go through a temp file + rename.

use blackbox_core::model::{GameRecord, Incident, SessionStats, Settings};
use blackbox_core::session;
use serde::{Deserialize, Serialize};
use std::collections::VecDeque;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

const CACHE: usize = 8;

pub fn write_atomic(path: &Path, bytes: &[u8]) -> io::Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    let tmp = path.with_extension("tmp");
    fs::write(&tmp, bytes)?;
    fs::rename(&tmp, path)
}

pub fn load_settings(dir: &Path) -> Settings {
    fs::read(dir.join("settings.json"))
        .ok()
        .and_then(|b| serde_json::from_slice::<Settings>(&b).ok())
        .unwrap_or_default()
        .sanitized()
}

pub fn save_settings(dir: &Path, s: &Settings) {
    match serde_json::to_vec_pretty(s) {
        Ok(b) => {
            if let Err(e) = write_atomic(&dir.join("settings.json"), &b) {
                log::warn!("settings not saved: {e}");
            }
        }
        Err(e) => log::warn!("settings not serialized: {e}"),
    }
}

#[derive(Debug)]
pub struct Store {
    dir: PathBuf,
    index: Vec<Incident>,
    cache: VecDeque<Incident>,
    retention: usize,
}

impl Store {
    pub fn open(data_dir: &Path, retention: u32) -> Store {
        let dir = data_dir.join("incidents");
        let index = fs::read(dir.join("index.json"))
            .ok()
            .and_then(|b| serde_json::from_slice::<Vec<Incident>>(&b).ok())
            .unwrap_or_default();
        let mut s = Store { dir, index, cache: VecDeque::with_capacity(CACHE), retention: retention as usize };
        s.enforce_retention();
        s
    }

    pub fn dir(&self) -> &Path {
        &self.dir
    }

    pub fn summaries(&self) -> &[Incident] {
        &self.index
    }

    pub fn len(&self) -> usize {
        self.index.len()
    }

    pub fn is_empty(&self) -> bool {
        self.index.is_empty()
    }

    pub fn unread(&self) -> u32 {
        self.index.iter().filter(|i| !i.read).count() as u32
    }

    pub fn set_retention(&mut self, retention: u32) {
        self.retention = retention as usize;
        if self.enforce_retention() {
            self.save_index();
        }
    }

    fn file(&self, id: &str) -> PathBuf {
        // Ids are generated by the engine (hex + dash); never trust them blindly for paths.
        let safe: String = id.chars().filter(|c| c.is_ascii_alphanumeric() || *c == '-').collect();
        self.dir.join(format!("{safe}.json"))
    }

    pub fn add(&mut self, inc: Incident) {
        match serde_json::to_vec(&inc) {
            Ok(b) => {
                if let Err(e) = write_atomic(&self.file(&inc.id), &b) {
                    log::warn!("incident not saved: {e}");
                }
            }
            Err(e) => log::warn!("incident not serialized: {e}"),
        }
        self.index.insert(0, inc.summary());
        self.remember(inc);
        self.enforce_retention();
        self.save_index();
    }

    fn remember(&mut self, inc: Incident) {
        self.cache.retain(|c| c.id != inc.id);
        if self.cache.len() == CACHE {
            self.cache.pop_back();
        }
        self.cache.push_front(inc);
    }

    pub fn get(&mut self, id: &str) -> Option<Incident> {
        let summary = self.index.iter().find(|i| i.id == id)?.clone();
        if let Some(c) = self.cache.iter().find(|c| c.id == id) {
            return Some(Incident { read: summary.read, ..c.clone() });
        }
        let full = fs::read(self.file(id)).ok().and_then(|b| serde_json::from_slice::<Incident>(&b).ok());
        let inc = match full {
            Some(f) => Incident { read: summary.read, ..f },
            None => summary,
        };
        self.remember(inc.clone());
        Some(inc)
    }

    pub fn mark_read(&mut self, id: Option<&str>) {
        let mut changed = false;
        for i in self.index.iter_mut().filter(|i| id.is_none_or(|id| i.id == id)) {
            changed |= !i.read;
            i.read = true;
        }
        if changed {
            self.save_index();
        }
    }

    pub fn delete(&mut self, id: &str) {
        let before = self.index.len();
        self.index.retain(|i| i.id != id);
        self.cache.retain(|i| i.id != id);
        let _ = fs::remove_file(self.file(id));
        if self.index.len() != before {
            self.save_index();
        }
    }

    pub fn clear(&mut self) {
        for i in std::mem::take(&mut self.index) {
            let _ = fs::remove_file(self.file(&i.id));
        }
        self.cache.clear();
        self.save_index();
    }

    pub fn export(&mut self, id: &str, to_dir: &Path) -> io::Result<PathBuf> {
        let inc = self.get(id).ok_or_else(|| io::Error::new(io::ErrorKind::NotFound, "incident not found"))?;
        let path = to_dir.join(format!("blackbox-incident-{}.json", inc.id));
        let bytes = serde_json::to_vec_pretty(&inc).map_err(io::Error::other)?;
        write_atomic(&path, &bytes)?;
        Ok(path)
    }

    fn enforce_retention(&mut self) -> bool {
        if self.index.len() <= self.retention {
            return false;
        }
        for old in self.index.split_off(self.retention) {
            let _ = fs::remove_file(self.file(&old.id));
        }
        true
    }

    fn save_index(&self) {
        match serde_json::to_vec(&self.index) {
            Ok(b) => {
                if let Err(e) = write_atomic(&self.dir.join("index.json"), &b) {
                    log::warn!("incident index not saved: {e}");
                }
            }
            Err(e) => log::warn!("incident index not serialized: {e}"),
        }
    }
}

/// Sessions kept per game, and games kept overall.
const SESSIONS_PER_GAME: usize = 20;
const MAX_GAMES: usize = 50;

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
struct GameEntry {
    name: String,
    sessions: Vec<SessionStats>,
    total_sessions: u32,
    total_play_sec: u64,
    /// Learned: the game hides the cursor during play (menus show it).
    cursor_game: Option<bool>,
}

/// Per-game play sessions: `games.json`, written once per finished session.
#[derive(Debug)]
pub struct GameStore {
    path: PathBuf,
    games: Vec<GameEntry>,
}

impl GameStore {
    pub fn open(data_dir: &Path) -> GameStore {
        let path = data_dir.join("games.json");
        let games =
            fs::read(&path).ok().and_then(|b| serde_json::from_slice::<Vec<GameEntry>>(&b).ok()).unwrap_or_default();
        GameStore { path, games }
    }

    fn record(e: &GameEntry, live: Option<&SessionStats>) -> GameRecord {
        GameRecord {
            name: e.name.clone(),
            last3: session::average(&e.sessions[..e.sessions.len().min(3)]),
            live: live.cloned(),
            total_sessions: e.total_sessions,
            total_play_sec: e.total_play_sec,
            last_played_ts: live.map(|l| l.end_ts).or_else(|| e.sessions.first().map(|s| s.end_ts)).unwrap_or(0),
            sessions: e.sessions.clone(),
        }
    }

    /// What earlier sessions learned about this game's cursor.
    pub fn cursor_hint(&self, name: &str) -> Option<bool> {
        self.games.iter().find(|g| g.name.eq_ignore_ascii_case(name)).and_then(|g| g.cursor_game)
    }

    /// Saves a finished session and returns the game's updated record.
    pub fn add(&mut self, s: SessionStats, cursor_game: Option<bool>) -> GameRecord {
        let i = match self.games.iter().position(|g| g.name.eq_ignore_ascii_case(&s.game)) {
            Some(i) => i,
            None => {
                self.games.push(GameEntry { name: s.game.clone(), ..Default::default() });
                self.games.len() - 1
            }
        };
        let mut e = self.games.remove(i);
        e.total_sessions += 1;
        // Time in the game (menus and loading included), not only gameplay.
        e.total_play_sec += s.all.as_ref().map_or(s.duration_sec, |a| a.duration_sec);
        if cursor_game.is_some() {
            e.cursor_game = cursor_game;
        }
        e.sessions.insert(0, s);
        e.sessions.truncate(SESSIONS_PER_GAME);
        self.games.insert(0, e); // most recently played first
        self.games.truncate(MAX_GAMES);
        self.save();
        Self::record(&self.games[0], None)
    }

    /// Every game, most recently played first; `live` is attached to its game (created if new).
    pub fn records(&self, live: Option<&SessionStats>) -> Vec<GameRecord> {
        let mut out: Vec<GameRecord> = Vec::with_capacity(self.games.len() + 1);
        if let Some(l) = live {
            if !self.games.iter().any(|g| g.name.eq_ignore_ascii_case(&l.game)) {
                out.push(Self::record(&GameEntry { name: l.game.clone(), ..Default::default() }, Some(l)));
            }
        }
        for g in &self.games {
            let l = live.filter(|l| l.game.eq_ignore_ascii_case(&g.name));
            out.push(Self::record(g, l));
        }
        out.sort_by_key(|r| std::cmp::Reverse(r.last_played_ts));
        out
    }

    pub fn delete(&mut self, name: &str) {
        let before = self.games.len();
        self.games.retain(|g| !g.name.eq_ignore_ascii_case(name));
        if self.games.len() != before {
            self.save();
        }
    }

    fn save(&self) {
        match serde_json::to_vec(&self.games) {
            Ok(b) => {
                if let Err(e) = write_atomic(&self.path, &b) {
                    log::warn!("game sessions not saved: {e}");
                }
            }
            Err(e) => log::warn!("game sessions not serialized: {e}"),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use blackbox_core::model::*;

    #[test]
    fn game_store_keeps_newest_sessions_and_averages_last_three() {
        let dir = temp_dir("games");
        let mut g = GameStore::open(&dir);
        for (i, fps) in [100.0, 200.0, 300.0, 400.0].into_iter().enumerate() {
            let rec = g.add(
                SessionStats {
                    id: format!("s{i}"),
                    game: "Game.exe".into(),
                    sessions: 1,
                    end_ts: i as i64,
                    duration_sec: 600,
                    fps_avg: fps,
                    ..Default::default()
                },
                Some(true),
            );
            assert_eq!(rec.total_sessions, i as u32 + 1);
        }
        g.add(SessionStats { game: "Other.exe".into(), end_ts: 10, duration_sec: 60, ..Default::default() }, None);
        assert_eq!(g.cursor_hint("GAME.exe"), Some(true));
        assert_eq!(g.cursor_hint("Other.exe"), None);
        let recs = GameStore::open(&dir).records(None);
        assert_eq!(recs[0].name, "Other.exe", "most recently played first");
        let game = &recs[1];
        assert_eq!(game.sessions[0].id, "s3", "newest session first");
        assert_eq!(game.last3.as_ref().unwrap().fps_avg, 300.0, "average of 400, 300, 200");
        assert_eq!(game.total_play_sec, 2400);

        let live = SessionStats { game: "New.exe".into(), end_ts: 99, ..Default::default() };
        let recs = g.records(Some(&live));
        assert_eq!(recs[0].name, "New.exe");
        assert!(recs[0].live.is_some() && recs[0].sessions.is_empty());

        g.delete("game.exe");
        assert_eq!(GameStore::open(&dir).records(None).len(), 1);
        let _ = fs::remove_dir_all(&dir);
    }

    fn incident(id: &str) -> Incident {
        Incident {
            id: id.into(),
            ts: 1,
            kind: IncidentKind::Hitch,
            severity: Severity::Major,
            magnitude: Magnitude { value: 120.0, unit: Unit::Ms },
            app: None,
            causes: vec![],
            ruled_out: vec![],
            read: false,
            timeline: Some(Timeline {
                t0: 0,
                t1: 1,
                marker_ts: 0,
                bucket_ms: 100,
                frames: vec![],
                dpc_max_us: vec![1, 2],
                isr_max_us: vec![],
                disk_mbps: vec![],
                disk_lat_ms: vec![],
                hard_faults: vec![],
                cpu_pct: vec![],
                gpu_pct: vec![],
                cpu_temp_c: vec![],
                gpu_temp_c: vec![],
                events: vec![],
            }),
            context: None,
        }
    }

    fn temp_dir(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("blackbox-test-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&d);
        d
    }

    #[test]
    fn add_get_read_delete_and_retention() {
        let dir = temp_dir("store");
        let mut s = Store::open(&dir, 2);
        s.add(incident("a"));
        s.add(incident("b"));
        s.add(incident("c"));
        assert_eq!(s.summaries().iter().map(|i| i.id.as_str()).collect::<Vec<_>>(), vec!["c", "b"]);
        assert!(s.summaries()[0].timeline.is_none(), "index keeps summaries only");
        assert!(!dir.join("incidents").join("a.json").exists(), "retention removes files");

        let mut reopened = Store::open(&dir, 2);
        assert_eq!(reopened.unread(), 2);
        let full = reopened.get("b").unwrap();
        assert_eq!(full.timeline.unwrap().dpc_max_us, vec![1, 2]);
        reopened.mark_read(Some("b"));
        assert_eq!(reopened.unread(), 1);
        reopened.delete("c");
        assert_eq!(reopened.len(), 1);
        reopened.clear();
        assert!(reopened.is_empty());
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn settings_roundtrip_and_defaults() {
        let dir = temp_dir("settings");
        assert_eq!(load_settings(&dir), Settings::default());
        let s = Settings { lang: Lang::Fr, retention: 5, ..Settings::default() };
        save_settings(&dir, &s);
        let back = load_settings(&dir);
        assert_eq!(back.lang, Lang::Fr);
        assert_eq!(back.retention, 10, "clamped");
        let _ = fs::remove_dir_all(&dir);
    }
}
