  defineProps<{
    text: string | number
    dot?: number // pitch in px
    color?: string
    ghost?: boolean // draw unlit dots faintly
    gap?: number // empty columns between glyphs
  }>(),
  { dot: 4, color: 'currentColor', ghost: false, gap: 1 },
