const ALIASES: Record<string, string> = { µ: 'U', '×': 'X', '–': '-', '—': '-', ' ': ' ', ' ': ' ' }

function glyph(ch: string): string[] {
  const up = ch.toUpperCase()
  if (FONT[up]) return FONT[up]
  const alias = ALIASES[ch]
  if (alias) return FONT[alias]
  const plain = up.normalize('NFD').replace(/[̀-ͯ]/g, '')
  return FONT[plain] ?? FONT['?']
}

const layout = computed(() => {
  const text = String(props.text)
  const p = props.dot
  const r = p * 0.36
  let col = 0
  let lit = ''
  let ghost = ''
  const dotPath = (cx: number, cy: number) => `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`
  for (const ch of text) {
    const rows = glyph(ch)
    const w = rows[0].length
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < w; x++) {
        const cx = (col + x) * p + p / 2
        const cy = y * p + p / 2
        if (rows[y][x] === '#') lit += dotPath(cx, cy)
        else if (props.ghost) ghost += dotPath(cx, cy)
      }
    }
    col += w + props.gap
  }
  col = Math.max(1, col - props.gap)
  return { lit, ghost, width: col * p, height: 7 * p }
})
