    :viewBox="`0 0 ${layout.width} ${layout.height}`"
    role="img"
    :aria-label="String(text)"
  >
    <path v-if="ghost" :d="layout.ghost" fill="var(--ghost)" />
    <path :d="layout.lit" :fill="color" />
  </svg>
</template>

